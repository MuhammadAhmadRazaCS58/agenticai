class DataAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the Data agent")
    route_response : str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")
    generated_sql_query : str = Field(default="", description="The SQL query generated for this turn, if the SQL agent handled it")
    sql_query_execution_result : str = Field(default="", description="The raw result of executing the SQL query, if the SQL agent handled it")
    final_answer : str = Field(default="", description="The final, user-facing answer text for this turn")
class RouterSchema(BaseModel):
    answer: Literal["sql","etl","general"] = Field(..., description="Classify the user's message: 'sql' if it asks a question about data already stored in the database, 'etl' if it asks to extract, transform, or load data from an external source or file, 'general' if it is a greeting, small talk, or any message unrelated to data operations (e.g. 'hi', 'hello', 'how are you', 'what can you do', 'thanks').")
    comments: str = Field(..., description="Additional comments or feedback regarding the classification of the user's question")
    
